export function getLocalizedWelcome(langCode: string = "en-IN"): LocalizedWelcomeContent {
  const norm = langCode === "auto" || !langCode ? "en-IN" : langCode;
  return WELCOME_LOCALIZATIONS[norm] || WELCOME_LOCALIZATIONS["en-IN"];
}

export function getWelcomeMessage(langCode: string = "en-IN"): string {
  return getLocalizedWelcome(langCode).welcomeMessage;
}

export function getSampleQueries(langCode: string = "en-IN"): string[] {
  return getLocalizedWelcome(langCode).sampleQueries;
}

export function getSampleQueriesHeading(langCode: string = "en-IN"): string {
  return getLocalizedWelcome(langCode).sampleHeading;
}

export function isWelcomeMessage(content: string): boolean {
  if (!content) return false;
  return Object.values(WELCOME_LOCALIZATIONS).some(
    (loc) => loc.welcomeMessage.trim() === content.trim()
  );
}
